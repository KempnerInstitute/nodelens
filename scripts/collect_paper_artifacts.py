def make_table_main_50(
    llama3_main: Dict[str, Any],
    llama3_noprotect: Optional[Dict[str, Any]],
    llama3_protect_baselines: Optional[Dict[str, Any]],
    out_path: Path,
    sparsity: float = 0.5,
    mode: str = "best",
) -> None:
    pruning_main = llama3_main.get("pruning_results") or {}
    evaluation_main = llama3_main.get("evaluation") or {}

    # Columns used in the draft Table 1
    cols: List[Tuple[str, str, int]] = [
        ("PPL$\\downarrow$", "perplexity", 1),
        ("MMLU", "accuracy_mmlu", 1),
        ("Hella", "accuracy_hellaswag", 1),
        ("PIQA", "accuracy_piqa", 1),
        ("BoolQ", "accuracy_boolq", 1),
    ]

    rows: List[List[str]] = []
    rows.append(["Method"] + [h for h, _, _ in cols])

    # Unpruned row
    baseline_ppl = evaluation_main.get("baseline_perplexity")
    baseline_metrics = evaluation_main.get("baseline_metrics") or {}
    unpruned_vals = {"perplexity": baseline_ppl, **(baseline_metrics if isinstance(baseline_metrics, dict) else {})}
    rows.append(["Unpruned"] + [_fmt(unpruned_vals.get(k), d) for _, k, d in cols])

    # Main rows from the "main" run
    methods_main: List[Tuple[str, str]] = [
        ("Magnitude (channel)", "weight_magnitude"),
        ("Wanda (channel)", "wanda"),
        ("SparseGPT (channel)", "sparsegpt"),
        ("Act. L2", "activation_l2_norm"),
        ("RQ", "rayleigh_quotient"),
        ("SCAR-LP", "scar_loss_proxy"),
        ("SCAR-Prot", "supernode_protection_score"),
        ("SCAR-Conn", "supernode_connectivity_score"),
    ]

    for label, metric in methods_main:
        picked_mode, entry = _pick_mode(pruning_main, metric=metric, sparsity=sparsity, mode=mode)
        if entry is None:
            rows.append([label] + ["--"] * len(cols))
            continue
        rows.append([label] + [_fmt(entry.get(k), d) for _, k, d in cols])

    # Optional extra rows (if those experiments are present)
    if llama3_noprotect is not None:
        pr = llama3_noprotect.get("pruning_results") or {}
        picked_mode, entry = _pick_mode(pr, metric="scar_loss_proxy", sparsity=sparsity, mode="low")
        if entry is not None:
            rows.append(["LP-no-protect"] + [_fmt(entry.get(k), d) for _, k, d in cols])

    if llama3_protect_baselines is not None:
        pr = llama3_protect_baselines.get("pruning_results") or {}
        for label, metric in [("Protect+Magnitude", "weight_magnitude"), ("Protect+Wanda", "wanda")]:
            picked_mode, entry = _pick_mode(pr, metric=metric, sparsity=sparsity, mode="low")
            if entry is not None:
                rows.append([label] + [_fmt(entry.get(k), d) for _, k, d in cols])

    content = latex_tabular(rows, align_spec="@{}l" + "c" * len(cols) + "@{}")
    write_text(out_path, content)


def make_table_sparsity_tradeoff(
    llama3_main: Dict[str, Any],
    out_path: Path,
    sparsities: List[float],
    mode: str = "low",
) -> None:
    pruning = llama3_main.get("pruning_results") or {}
    baseline_ppl = (llama3_main.get("evaluation") or {}).get("baseline_perplexity")

    methods: List[Tuple[str, str]] = [
        ("Wanda (channel)", "wanda"),
        ("SparseGPT (channel)", "sparsegpt"),
        ("SCAR-LP", "scar_loss_proxy"),
        ("SCAR-Prot", "supernode_protection_score"),
        ("SCAR-Conn", "supernode_connectivity_score"),
    ]

    header = ["Method"] + [f"{int(100*s)}\\%" for s in sparsities]
    rows: List[List[str]] = [header]
    if baseline_ppl is not None:
        rows.append(["Baseline"] + [_fmt(baseline_ppl, 1)] * len(sparsities))

    for label, metric in methods:
        row = [label]
        for s in sparsities:
            picked_mode, entry = _pick_mode(pruning, metric=metric, sparsity=s, mode=mode)
            row.append(_fmt(entry.get("perplexity") if entry else None, 1))
        rows.append(row)

    content = latex_tabular(rows, align_spec="@{}l" + "c" * len(sparsities) + "@{}")
    write_text(out_path, content)


def make_table_generalization(
    model_results: List[Tuple[str, Dict[str, Any]]],
    out_path: Path,
    sparsity: float = 0.5,
    mode: str = "best",
) -> None:
    rows: List[List[str]] = []
    rows.append(["Model", "Method", "PPL$\\downarrow$", "MMLU", "Avg.$\\uparrow$"])

    for model_label, res in model_results:
        pr = res.get("pruning_results") or {}
        # Wanda baseline
        _, wanda = _pick_mode(pr, metric="wanda", sparsity=sparsity, mode=mode)
        _, scar = _pick_mode(pr, metric="supernode_connectivity_score", sparsity=sparsity, mode=mode)

        def avg_acc(entry: Optional[Dict[str, Any]]) -> Optional[float]:
            if not entry:
                return None
            accs = [float(v) for k, v in entry.items() if isinstance(k, str) and k.startswith("accuracy_") and v is not None]
            return sum(accs) / len(accs) if accs else None

        for method_label, entry in [("Wanda (channel)", wanda), ("SCAR-Conn", scar)]:
            rows.append(
                [
                    model_label,
                    method_label,
                    _fmt(entry.get("perplexity") if entry else None, 1),
                    _fmt(entry.get("accuracy_mmlu") if entry else None, 1),
                    _fmt(avg_acc(entry), 1),
                ]
            )

    content = latex_tabular(rows, align_spec="@{}llccc@{}")
    write_text(out_path, content)


def make_table_halo_redundancy(
    llama3_main: Dict[str, Any],
    out_path: Path,
) -> None:
    halo = llama3_main.get("halo_analysis") or {}
    agg = halo.get("aggregate") or {}

    # The current analysis uses |corr|; we expose it directly for the draft table.
    rows: List[List[str]] = []
    rows.append(["Group Pair", "Mean", "Std"])

    def get(group: str, key: str) -> Any:
        return (agg.get(group) or {}).get(key)

    rows.append(["Within-Halo", _fmt(get("halo_halo", "mean"), 3), _fmt(get("halo_halo", "std"), 3)])
    rows.append(["Within-Non-Halo", _fmt(get("non_halo", "mean"), 3), _fmt(get("non_halo", "std"), 3)])
    rows.append(["Cross (Halo $\\leftrightarrow$ Non-Halo)", _fmt(get("cross", "mean"), 3), _fmt(get("cross", "std"), 3)])

    content = latex_tabular(rows, align_spec="@{}lcc@{}")
    write_text(out_path, content)


