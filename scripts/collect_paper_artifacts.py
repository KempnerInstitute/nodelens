#!/usr/bin/env python3
"""
Collect SCAR paper artifacts (tables + key figures) from experiment job directories.

This script is meant to be run AFTER the SLURM batch suite finishes.

What it does:
- Finds the latest job directory for each expected experiment name under --results-base
- Loads the corresponding results_*.json
- Generates LaTeX table snippets into drafts/LLM_prune/paper_artifacts/tables/
- Copies a small set of "paper figure" images into drafts/LLM_prune/ as the placeholder_*.png files
  used by `drafts/LLM_prune/scar_paper_icml_v5.tex` (so the paper auto-fills without manual edits).

Example:
  python scripts/collect_paper_artifacts.py \
    --results-base /n/holylfs06/LABS/kempner_project_b/Lab/alignment/Prune_LLM \
    --draft-dir /n/holylabs/kempner_dev/Users/hsafaai/Code/alignment/drafts/LLM_prune
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Tuple


# -----------------------------
# Helpers
# -----------------------------


def _latest_results_json(job_dir: Path) -> Optional[Path]:
    candidates: List[Path] = []
    if (job_dir / "results").exists():
        candidates.extend(sorted((job_dir / "results").glob("results_*.json")))
    candidates.extend(sorted(job_dir.glob("results_*.json")))
    if not candidates:
        return None
    candidates.sort(key=lambda p: p.stat().st_mtime, reverse=True)
    return candidates[0]


def find_latest_job_dir(results_base: Path, experiment_name: str) -> Optional[Path]:
    """
    Job directories are created as:
      {experiment_name}_{timestamp}_{job_id}/
    """
    if not results_base.exists():
        return None
    candidates = [p for p in results_base.iterdir() if p.is_dir() and p.name.startswith(f"{experiment_name}_")]
    candidates.sort(key=lambda p: p.stat().st_mtime, reverse=True)
    for job_dir in candidates:
        if _latest_results_json(job_dir) is not None:
            return job_dir
    return None


def load_results(job_dir: Path) -> Dict[str, Any]:
    path = _latest_results_json(job_dir)
    if path is None:
        raise FileNotFoundError(f"No results_*.json found in {job_dir} or {job_dir/'results'}")
    return json.loads(path.read_text())


def _get_pruned_entry(
    pruning_results: Dict[str, Any],
    metric: str,
    mode: str,
    sparsity: float,
) -> Optional[Dict[str, Any]]:
    for v in pruning_results.values():
        if not isinstance(v, dict):
            continue
        if v.get("metric") == metric and v.get("mode") == mode and float(v.get("sparsity", -1)) == float(sparsity):
            return v
    return None


def _pick_mode(
    pruning_results: Dict[str, Any],
    metric: str,
    sparsity: float,
    mode: str,
) -> Tuple[str, Optional[Dict[str, Any]]]:
    """
    mode:
      - "low" or "high": choose that mode
      - "best": choose the better of low/high by perplexity
    """
    if mode in {"low", "high"}:
        return mode, _get_pruned_entry(pruning_results, metric=metric, mode=mode, sparsity=sparsity)

    low = _get_pruned_entry(pruning_results, metric=metric, mode="low", sparsity=sparsity)
    high = _get_pruned_entry(pruning_results, metric=metric, mode="high", sparsity=sparsity)

    def ppl(x: Optional[Dict[str, Any]]) -> float:
        if not x:
            return float("inf")
        v = x.get("perplexity")
        return float(v) if v is not None else float("inf")

    if ppl(low) <= ppl(high):
        return "low", low
    return "high", high


def _fmt(x: Any, digits: int = 1) -> str:
    if x is None:
        return "--"
    try:
        xf = float(x)
    except Exception:
        return "--"
    if xf != xf:  # NaN
        return "--"
    return f"{xf:.{digits}f}"


def write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)


def latex_tabular(rows: List[List[str]], align_spec: str) -> str:
    lines = []
    lines.append("% Auto-generated by scripts/collect_paper_artifacts.py")
    lines.append(f"\\begin{{tabular}}{{{align_spec}}}")
    lines.append("\\toprule")
    for i, r in enumerate(rows):
        lines.append(" & ".join(r) + " \\\\")
        if i == 0:
            lines.append("\\midrule")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("")
    return "\n".join(lines)


def safe_copy(src: Path, dst: Path) -> bool:
    if not src.exists():
        return False
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    return True


